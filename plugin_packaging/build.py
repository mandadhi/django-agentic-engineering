"""Deterministic packaging of the Django Engineering Pack as a Claude Code plugin (Phase 4).

The pack root *is* the plugin root: ``.claude-plugin/plugin.json`` sits next to the canonical
``agents/``, ``commands/``, ``skills/``, ``rules/``, ``templates/`` and ``references/``. Claude Code
loads those folders in place, so no skill, rule, agent, command, template or reference is
copied. Only two things are derived, and both are traceable and drift-checked:

1. ``hooks/security-policy.json``: the standalone guard's policy, built from
   ``config/security-config.yaml`` (harness, reused unchanged), each agent's ``tools``
   frontmatter and ``plugin_packaging/standalone-security.yaml``.
2. The ``skills:`` line in each Django agent's frontmatter: the agent's skills and rules exactly
   as registered in ``config/agent-registry.yaml``, namespaced ``django-engineering:<id>``.
   Claude Code preloads them into the subagent, which is what the harness does with the registry.
   The harness ignores this key (it reads skills only from the registry).
3. ``hooks/shell_syntax.py`` (Phase 5.1): a byte-for-byte copy of the harness's shell command
   analyser ``core/shell_syntax.py`` (standard library only), so both guards parse commands with
   the same code while the installed plugin stays independent of the harness.

``build`` writes them; ``check`` reports every difference and every structural problem without
writing. Neither needs the parent repository or runs the Python harness.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

PACK_ROOT = Path(__file__).resolve().parents[1]
PLUGIN_NAME = "django-engineering"
PROJECT_PREFIX = "projects/django-agentic-engineering/"

MANIFEST = Path(".claude-plugin/plugin.json")
HOOKS_FILE = Path("hooks/hooks.json")
POLICY_FILE = Path("hooks/security-policy.json")
GUARD_FILE = Path("hooks/django_pack_guard.py")
SHELL_SYNTAX_SOURCE = Path("core/shell_syntax.py")
SHELL_SYNTAX_COPY = Path("hooks/shell_syntax.py")
STANDALONE_POLICY = Path("plugin_packaging/standalone-security.yaml")
SECURITY_CONFIG = Path("config/security-config.yaml")
AGENT_REGISTRY = Path("config/agent-registry.yaml")
SKILL_REGISTRY = Path("config/skill-registry.yaml")

#: Plugin component folders, as declared in plugin.json (Claude Code also scans skills/ by default).
SKILL_DIRS = ("skills", "rules")
EXPECTED_COUNTS = {"agents": 9, "commands": 9, "skills": 12, "rules": 12}
WRITE_MODES = {"read-only", "documentation-only", "confirm-writes", "workspace-write"}
#: Strictest first (same order as core.plugin_policy.MODE_ORDER): a mode security-config assigns to a
#: pack agent can only make the standalone mode stricter.
MODE_ORDER = ("read-only", "documentation-only", "confirm-writes", "workspace-write")
CAPABILITIES = {"read", "write", "delete", "execute", "network", "unknown"}
SKILLS_COMMENT = "# skills: generated by `python -m plugin_packaging build` from config/agent-registry.yaml"

_FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.S)


class PackagingError(Exception):
    """Raised when the canonical sources cannot be packaged (missing or inconsistent files)."""


@dataclass
class Report:
    problems: list[str] = field(default_factory=list)
    written: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.problems


# ---------------------------------------------------------------------- canonical sources


def _yaml(root: Path, rel: Path) -> Any:
    path = root / rel
    if not path.is_file():
        raise PackagingError(f"missing canonical source: {rel.as_posix()}")
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _text(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def frontmatter(path: Path) -> dict[str, Any]:
    match = _FRONTMATTER.match(_text(path))
    if not match:
        raise PackagingError(f"{path.name}: no YAML frontmatter")
    return yaml.safe_load(match.group(1)) or {}


def _as_list(value: Any) -> list[str]:
    if value is None:
        return []
    if isinstance(value, str):
        return [part.strip() for part in value.split(",") if part.strip()]
    return [str(part).strip() for part in value]


def _pack_path(entry: dict[str, Any]) -> str | None:
    """Pack-relative path of a registry entry that belongs to the pack, else None.

    Since Phase 5 pack entries name the plugin (``plugin: django-engineering``, path relative to
    the pack root). The Phase 3 form (``source: local``, path under ``projects/django-agentic-engineering/``)
    is still recognised so either registry layout packages identically.
    """
    rel = str(entry["path"])
    if entry.get("plugin") == PLUGIN_NAME and entry.get("source") == "plugin":
        return rel
    if entry.get("source") == "local" and rel.startswith(PROJECT_PREFIX):
        return rel[len(PROJECT_PREFIX):]
    return None


def pack_agents(root: Path = PACK_ROOT) -> dict[str, list[str]]:
    """Django agent id -> registered skill and rule ids, in registry order (pack agents only)."""
    registry = _yaml(root, AGENT_REGISTRY)
    skills = {s["id"]: s for s in _yaml(root, SKILL_REGISTRY)["skills"]}
    agents: dict[str, list[str]] = {}
    for agent in registry["agents"]:
        if not (_pack_path(agent) or "").startswith("agents/"):
            continue
        ids = list(agent.get("skills", []))
        for skill_id in ids:
            spec = skills.get(skill_id)
            if spec is None:
                raise PackagingError(f"{agent['id']}: skill '{skill_id}' is not in the skill registry")
            rel = _pack_path(spec)
            if rel is None:
                raise PackagingError(f"{agent['id']}: skill '{skill_id}' is not part of the pack ({spec['path']})")
            if not (root / rel / "SKILL.md").is_file():
                raise PackagingError(f"{agent['id']}: {rel}/SKILL.md does not exist")
        agents[agent["id"]] = ids
    return agents


def namespaced(skill_id: str) -> str:
    return f"{PLUGIN_NAME}:{skill_id}"


# ---------------------------------------------------------------------- derived: security policy


def build_policy(root: Path = PACK_ROOT) -> dict[str, Any]:
    security = _yaml(root, SECURITY_CONFIG)
    standalone = _yaml(root, STANDALONE_POLICY)
    if standalone.get("plugin") != PLUGIN_NAME:
        raise PackagingError(f"{STANDALONE_POLICY.as_posix()}: plugin must be '{PLUGIN_NAME}'")
    registered = pack_agents(root)
    modes: dict[str, str] = standalone.get("agents") or {}
    if set(modes) != set(registered):
        raise PackagingError(f"{STANDALONE_POLICY.as_posix()}: agents {sorted(modes)} != registered pack agents "
                             f"{sorted(registered)}")
    tool_overrides = {o["agent_id"]: list(o.get("deny", [])) for o in security.get("tools", {}).get("agents", [])}
    harness_modes = {o["agent_id"]: o["write_mode"] for o in security.get("tools", {}).get("agents", [])
                     if o.get("write_mode")}
    write_modes = _write_modes(security)
    agents: dict[str, Any] = {}
    for agent_id in sorted(registered):
        mode = modes[agent_id]
        if mode not in WRITE_MODES:
            raise PackagingError(f"{agent_id}: unknown write mode '{mode}'")
        if agent_id in harness_modes:                     # harness policy: never widened by the plugin's file
            if harness_modes[agent_id] not in WRITE_MODES:
                raise PackagingError(f"{agent_id}: unknown write mode '{harness_modes[agent_id]}' in security-config")
            mode = min(mode, harness_modes[agent_id], key=MODE_ORDER.index)
        meta = frontmatter(root / "agents" / f"{agent_id}.md")
        tools = _as_list(meta.get("tools"))
        if not tools:
            raise PackagingError(f"{agent_id}: frontmatter declares no tools")
        deny = sorted(set(_as_list(meta.get("disallowedTools"))) | set(tool_overrides.get(agent_id, [])))
        agents[agent_id] = {"mode": mode, "tools": tools, "deny": deny}
    commands = security.get("commands", {})
    shell = security.get("shell") or {}
    for key in ("destructive_programs", "sensitive_variables"):
        if key not in shell:
            raise PackagingError(f"{SECURITY_CONFIG.as_posix()}: shell.{key} is required by the standalone guard")
    re.compile(shell["sensitive_variables"])
    return {
        "_generated": {
            "by": "python -m plugin_packaging build",
            "do_not_edit": "Edit the sources and rebuild; tests fail when this file drifts from them.",
            "sources": [SECURITY_CONFIG.as_posix(), "agents/<id>.md (frontmatter tools, disallowedTools)",
                        AGENT_REGISTRY.as_posix(), STANDALONE_POLICY.as_posix()],
        },
        "schema_version": "1.0",
        "plugin": PLUGIN_NAME,
        "tools_deny": list(security.get("tools", {}).get("deny", [])),
        "paths_deny": list(security.get("paths", {}).get("deny", [])),
        "commands_deny": [_rule(r) for r in commands.get("deny", [])],
        "commands_require_approval": [_rule(r) for r in commands.get("require_approval", [])],
        "secret_patterns": [{"id": p["id"], "regex": p["regex"]} for p in security.get("secrets", {}).get("patterns", [])],
        "redaction": {"enabled": bool(security.get("redaction", {}).get("enabled", True)),
                      "replacement": security.get("redaction", {}).get("replacement", "[REDACTED]")},
        "documentation_paths": list(standalone.get("documentation_paths", [])),
        "read_only_commands": [_rule(r) for r in standalone.get("read_only_commands", [])],
        "write_modes": write_modes,
        "shell": {"destructive_programs": list(shell["destructive_programs"]),
                  "sensitive_variables": shell["sensitive_variables"]},
        "agents": agents,
    }


def _write_modes(security: dict[str, Any]) -> dict[str, Any]:
    """security-config ``write_modes`` (SEC-06): every mode stated, capabilities and outcomes known."""
    table = security.get("write_modes") or {}
    if set(table) != WRITE_MODES:
        raise PackagingError(f"{SECURITY_CONFIG.as_posix()}: write_modes must state {sorted(WRITE_MODES)}")
    out: dict[str, Any] = {}
    for mode in MODE_ORDER:
        spec = table[mode]
        allow = list(spec.get("allow", []))
        if not set(allow) <= CAPABILITIES or spec.get("otherwise", "deny") not in ("deny", "approve"):
            raise PackagingError(f"{SECURITY_CONFIG.as_posix()}: write_modes.{mode} is invalid")
        out[mode] = {"allow": allow, "otherwise": spec.get("otherwise", "deny"), "shell": bool(spec.get("shell", True))}
    return out


def _rule(rule: dict[str, Any]) -> dict[str, str]:
    re.compile(rule["regex"])                                     # fail at build time, not in the hook
    return {"id": rule["id"], "regex": rule["regex"], "description": rule.get("description", "")}


def render_policy(policy: dict[str, Any]) -> str:
    return json.dumps(policy, indent=2, sort_keys=False, ensure_ascii=False) + "\n"


# ---------------------------------------------------------------------- derived: agent skills line


def skills_line(skill_ids: list[str]) -> str:
    return "skills: [" + ", ".join(namespaced(s) for s in skill_ids) + "]"


def with_skills_line(text: str, skill_ids: list[str]) -> str:
    """Agent Markdown with exactly one generated ``skills:`` line (after ``model:``)."""
    newline = "\r\n" if "\r\n" in text else "\n"
    body = text.replace("\r\n", "\n")
    match = _FRONTMATTER.match(body)
    if not match:
        raise PackagingError("agent file has no frontmatter")
    lines = [line for line in match.group(1).split("\n")
             if not line.startswith("skills:") and line != SKILLS_COMMENT]
    try:
        at = next(i for i, line in enumerate(lines) if line.startswith("model:")) + 1
    except StopIteration:
        raise PackagingError("agent frontmatter has no model line") from None
    lines[at:at] = [SKILLS_COMMENT, skills_line(skill_ids)]
    rebuilt = "---\n" + "\n".join(lines) + "\n---\n" + body[match.end():]
    return rebuilt.replace("\n", newline)


# ---------------------------------------------------------------------- structure checks


def structure_problems(root: Path = PACK_ROOT) -> list[str]:
    problems: list[str] = []
    manifest_path = root / MANIFEST
    if not manifest_path.is_file():
        return [f"missing {MANIFEST.as_posix()}"]
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("name") != PLUGIN_NAME:
        problems.append(f"plugin.json name is {manifest.get('name')!r}, expected {PLUGIN_NAME!r}")
    declared = manifest.get("skills")
    if sorted(declared or []) != sorted(f"./{d}/" for d in SKILL_DIRS):
        problems.append(f"plugin.json skills must be {[f'./{d}/' for d in SKILL_DIRS]}, got {declared}")
    if "hooks" in manifest:
        problems.append("plugin.json must not declare hooks: Claude Code loads ./hooks/hooks.json by default, "
                        "and declaring it again loads it twice")

    agents = sorted(p.stem for p in (root / "agents").glob("*.md") if not p.stem.isupper())
    commands = sorted(p.stem for p in (root / "commands").glob("*.md") if not p.stem.isupper())
    # agents/ and commands/ also hold README.md. Listing the files explicitly replaces the folder
    # scan (verified with CLI 2.1.319), so the READMEs never load as an agent or a command.
    for key, found in (("agents", agents), ("commands", commands)):
        expected = [f"./{key}/{name}.md" for name in found]
        if manifest.get(key) != expected:
            problems.append(f"plugin.json {key} must list exactly the canonical files {expected}, "
                            f"got {manifest.get(key)}")
    skills = sorted(p.parent.name for p in (root / "skills").glob("*/SKILL.md"))
    rules = sorted(p.parent.name for p in (root / "rules").glob("*/SKILL.md"))
    for kind, found in (("agents", agents), ("commands", commands), ("skills", skills), ("rules", rules)):
        if len(found) != EXPECTED_COUNTS[kind]:
            problems.append(f"{kind}: expected {EXPECTED_COUNTS[kind]}, found {len(found)}")
    # Every component name must be unique inside the plugin. Claude Code exposes skills as slash
    # commands too, and a command shadows a skill of the same name (verified with CLI 2.1.319).
    names: dict[str, str] = {}
    for kind, found in (("agent", agents), ("command", commands), ("skill", skills), ("rule", rules)):
        for name in found:
            if name in names:
                problems.append(f"name collision: {kind} '{name}' and {names[name]} '{name}'")
            names.setdefault(name, kind)
    for skill_dir, found in (("skills", skills), ("rules", rules)):
        for name in found:
            meta = frontmatter(root / skill_dir / name / "SKILL.md")
            if meta.get("name") != name:
                problems.append(f"{skill_dir}/{name}/SKILL.md: name is {meta.get('name')!r}")
    for path in (HOOKS_FILE, GUARD_FILE, SHELL_SYNTAX_COPY):
        if not (root / path).is_file():
            problems.append(f"missing {path.as_posix()}")
    return problems


# ---------------------------------------------------------------------- staging (installable bundle)

#: What an installed plugin needs at run time. Everything else (the Python harness, tests,
#: config, .venv, var/, local settings) stays out of the bundle.
STAGE_DIRS = ("agents", "commands", "skills", "rules", "templates", "references")
STAGE_FILES = (MANIFEST, HOOKS_FILE, GUARD_FILE, SHELL_SYNTAX_COPY, POLICY_FILE, Path("hooks/README.md"),
               Path("README.md"))
STAGE_RECORD = "STAGED-FROM.json"
MARKETPLACE_NAME = "django-engineering-pack"


def stage(dest: Path, root: Path = PACK_ROOT) -> Report:
    """Export the plugin's runtime files, byte for byte, into ``dest`` with a local marketplace.

    Claude Code copies a plugin folder into its cache on install, ignoring .gitignore, so
    installing straight from a working copy would also copy .venv and local settings. The
    staged folder is a build output: regenerate it, never edit it. ``STAGED-FROM.json`` maps
    every staged file to its canonical source with a SHA-256 for traceability.
    """
    import hashlib
    import shutil

    report = run(root, write=False)
    if not report.ok:
        report.problems.insert(0, "refusing to stage: packaging is not consistent with its canonical sources")
        return report
    dest = dest.resolve()
    if dest == root.resolve() or root.resolve() in dest.parents:
        report.problems.append(f"stage destination must be outside the pack: {dest}")
        return report
    if dest.exists():
        if not (dest / STAGE_RECORD).is_file():
            report.problems.append(f"{dest} exists and is not a previous stage (no {STAGE_RECORD}); not overwriting it")
            return report
        shutil.rmtree(dest)

    files = [p for d in STAGE_DIRS for p in sorted((root / d).rglob("*")) if p.is_file() and "__pycache__" not in p.parts]
    files += [root / f for f in STAGE_FILES]
    record = []
    for source in files:
        rel = source.relative_to(root)
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        record.append({"path": rel.as_posix(), "source": rel.as_posix(),
                       "sha256": hashlib.sha256(source.read_bytes()).hexdigest()})
        report.written.append(rel.as_posix())

    plugin = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    marketplace = {
        "name": MARKETPLACE_NAME,
        "owner": plugin["author"],
        "metadata": {"description": "Local marketplace for the staged Django Engineering Pack plugin "
                                    "(generated by `python -m plugin_packaging stage`)."},
        "plugins": [{"name": plugin["name"], "source": "./", "description": plugin["description"],
                     "version": plugin["version"], "author": plugin["author"], "category": "backend",
                     "keywords": plugin["keywords"]}],
    }
    (dest / ".claude-plugin" / "marketplace.json").write_text(json.dumps(marketplace, indent=2) + "\n", encoding="utf-8")
    (dest / STAGE_RECORD).write_text(json.dumps({
        "generated_by": "python -m plugin_packaging stage",
        "do_not_edit": "Build output. Edit the canonical pack and stage again.",
        "pack_root": str(root.resolve()),
        "plugin": plugin["name"], "version": plugin["version"],
        "files": record}, indent=2) + "\n", encoding="utf-8")
    report.written += [".claude-plugin/marketplace.json", STAGE_RECORD]
    return report


# ---------------------------------------------------------------------- entry points


def run(root: Path = PACK_ROOT, *, write: bool) -> Report:
    report = Report()
    try:
        registered = pack_agents(root)
        policy_text = render_policy(build_policy(root))
    except PackagingError as exc:
        report.problems.append(str(exc))
        return report

    targets: list[tuple[Path, str]] = [(root / POLICY_FILE, policy_text)]
    if (root / SHELL_SYNTAX_SOURCE).is_file():     # absent only in a pack copied without the harness code
        targets.append((root / SHELL_SYNTAX_COPY, (root / SHELL_SYNTAX_SOURCE).read_bytes().decode("utf-8")))
    for agent_id, skill_ids in registered.items():
        path = root / "agents" / f"{agent_id}.md"
        if not path.is_file():
            report.problems.append(f"registered agent file missing: agents/{agent_id}.md")
            continue
        current = path.read_bytes().decode("utf-8")
        try:
            targets.append((path, with_skills_line(current, skill_ids)))
        except PackagingError as exc:
            report.problems.append(f"agents/{agent_id}.md: {exc}")

    for path, expected in targets:
        current = path.read_bytes().decode("utf-8") if path.is_file() else None
        if current == expected:
            continue
        rel = path.relative_to(root).as_posix()
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected.encode("utf-8"))
            report.written.append(rel)
        else:
            report.problems.append(f"{rel} is out of date with its canonical sources "
                                   f"(run `python -m plugin_packaging build`)")
    report.problems.extend(structure_problems(root))
    return report
